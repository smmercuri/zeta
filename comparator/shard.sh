#!/usr/bin/env bash
# Check several certificate batches in one comparator run.
#
# Each batch has its own target `comparator/Batches/<Method>/BatchNNNN/` (written by
# `python/src/data_gen/gen_comparator.py`): its challenge states the batch's `BatchSpec` and its
# solution cites the batch's theorem. Any one of them can be run on its own, but every comparator
# run re-exports and re-checks the dependencies the batches share (a slice of Mathlib and the
# certificate lemmas), so a shard runs N targets at once: this writes the umbrella
# `comparator/Shard/{Challenge,Solution}.lean`, importing the N batches' challenges and solutions,
# and a config listing their N theorems.
#
#   comparator/shard.sh RiemannSiegel/Batch0001 RiemannSiegel/Batch0002 …
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
OUT=comparator/Shard
mkdir -p "$OUT"

challenge="" solution="" names=""
for b in "$@"; do
  d=comparator/Batches/$b
  [[ -f $d/config.json ]] || { echo "shard.sh: no comparator target $d (run gen_comparator.py)" >&2; exit 2; }
  mod="Batches.${b//\//.}"
  challenge+="import $mod.Challenge"$'\n'
  solution+="import $mod.Solution"$'\n'
  name=$(sed -nE 's/.*"(Comparator\.[A-Za-z0-9_]+)".*/\1/p' "$d/config.json")
  names+="${names:+, }\"$name\""
done

printf '/- Generated by comparator/shard.sh; not checked in. -/\n%s' "$challenge" > "$OUT/Challenge.lean"
printf '/- Generated by comparator/shard.sh; not checked in. -/\n%s' "$solution" > "$OUT/Solution.lean"
cat > "$OUT/config.json" <<JSON
{
    "challenge_module": "Shard.Challenge",
    "solution_module": "Shard.Solution",
    "theorem_names": [$names],
    "permitted_axioms": ["propext", "Quot.sound", "Classical.choice"],
    "enable_nanoda": false
}
JSON
exec comparator/run.sh "$OUT/config.json"
