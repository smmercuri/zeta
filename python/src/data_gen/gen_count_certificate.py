"""Generate `CountCertificates.lean`: the concrete `CertifiedZeroCount` instance tying the generated
gram-block sequence (`certifiedGramBlockSeq`) and zero-interval bundle (`certifiedZeroIntervals`)
together. This is the *only* data-specific artifact: the `RiemannHypothesisUpTo (gramPoint minIdx)`
statement it feeds is generic (proved once, for any `CertifiedZeroCount`, in `RiemannHypothesisUpTo.lean`).

Reads only the zero store, and only to learn how the last batch renders its endpoints: the `below`
proof reaches the last interval through the assembler's `certifiedZeroIntervals_getLast?` plus
unification, never by name (a metaprogram-built batch names none of its intervals). The count and
the below-gram-point bound are otherwise data-independent (discharged via exposed lemmas).

The headline `Zeta/Main.lean` and the comparator challenge `comparator/Main/` are hand-written and
state their height `H` by hand. Before writing anything, the generator checks that they state the
same `H` and that it is the height the certificates support, `⌊gp1.fst⌋` for the first gram point
exactly as `gen_gram_certificates.py` emits it (or a smaller `--height`); otherwise it stops.
"""
import argparse
import math
import re
from decimal import Decimal
from pathlib import Path

from data_gen.gen_gram_certificates import parse_gram_points
from data_gen.gen_zero_certificates import (
    default_stores,
    plan_batches,
    write_module,
)

ROOT = Path(__file__).resolve().parents[3]


def gen_count_certificate(unfolds: str, zsrc: str, native: bool = False) -> str:
    """The module text. `native` builds it on the native assembler (`Native.Certificates`) instead,
    as `Native.certifiedZeroCount`."""
    script = "gen_native_certificates.py" if native else "gen_count_certificate.py"
    assembler = "Native.Certificates" if native else "Zeta.Zeros.Certificates"
    opens = " Native.Certificates" if native else ""
    ns_open, ns_close = ("namespace Native\n\n", "\nend Native\n") if native else ("", "")
    return f"""/-
Copyright (c) 2026 Salvatore Mercuri, Bhavik Mehta. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Salvatore Mercuri, Bhavik Mehta
-/
/-
AUTO-GENERATED by `python/src/data_gen/{script}` from
{zsrc}
Do not edit by hand: regenerate instead.

The concrete `CertifiedZeroCount` instance: the generated gram-block sequence
`certifiedGramBlockSeq` together with the zero-interval bundle `certifiedZeroIntervals`, with the
Turing count-match and the below-gram-point bound discharged. Feed it to the generic
`riemannHypothesisUpTo` (in `RiemannHypothesisUpTo.lean`) to obtain `RiemannHypothesisUpTo`
up to the head gram point.
-/
module

public import Zeta.Zeros.Count
public import Zeta.Gram.Certificates
public import {assembler}

@[expose] public section

open Set Zeta.Certificates Zeta.Certificates.Gram{opens}

{ns_open}/-- The co-generated certificate: the gram sequence and the zero list, with the Turing count-match
(`certifiedZeroIntervals_length` against `minIdx`) and the below-gram-point bound, both discharged
from the assembler's exported `length`/`getLast?` lemmas plus the gram lower bound.
`noncomputable` because it holds `certifiedZeroIntervals`, a join of `Classical.choose`n batch
bundles with `Enclosure.sfrac` endpoints. -/
noncomputable def certifiedZeroCount : CertifiedZeroCount where
  toCertifiedGramBlockSeq := certifiedGramBlockSeq
  toCertifiedZeroIntervals := certifiedZeroIntervals
  count := by rw [certifiedZeroIntervals_length]; decide
  below := by
    refine certifiedZeroIntervals.height_le_of_getLast?_snd certifiedZeroIntervals_getLast? ?_
    refine le_trans ?_ certifiedGramBlockSeq.head_left_le_gramPoint
    norm_num [certifiedGramBlockSeq{unfolds}]
{ns_close}
end
"""


def gram_head(gram: Path) -> Decimal:
    """`gp1.fst`, the first gram point's lower end, exactly as `gen_gram_certificates.py` emits it."""
    pts = parse_gram_points(gram / "gram_block.txt")
    if not pts:
        raise SystemExit(f"{gram}: no gram points in gram_block.txt")
    return Decimal(pts[0][1])


def default_gram() -> Path:
    """The gram store under `python/out/`, if there is exactly one."""
    found = sorted(p.parent for p in (ROOT / "python" / "out").glob("*/gram/manifest.json"))
    if len(found) != 1:
        raise SystemExit(f"{len(found)} gram stores under python/out/: pass one with --gram")
    return found[0]


def stated_height(path: Path) -> int:
    """The `H` of the `theorem riemannHypothesisUpTo_<H>` that the hand-written `path` states."""
    m = re.search(r"theorem riemannHypothesisUpTo_(\d+)\b", path.read_text())
    if m is None:
        raise SystemExit(f"no `theorem riemannHypothesisUpTo_<H>` in {path.relative_to(ROOT)}")
    return int(m.group(1))


def check_heights(height: int, top: int) -> None:
    """Stop, writing nothing, unless `Zeta/Main.lean` and `comparator/Main` both state `height`;
    `top` is the largest height the certificates support."""
    main = stated_height(ROOT / "Zeta" / "Main.lean")
    challenge = stated_height(ROOT / "comparator" / "Main" / "Challenge.lean")
    if main == challenge == height:
        return
    hint = (f"; or pass --height {main}, which the certificates support"
            if main == challenge and main <= top else "")
    raise SystemExit(
        f"Zeta/Main.lean states height {main}, comparator/Main {challenge}, and the certificates "
        f"give height {height} (nothing written).\nBoth are hand-written: change Zeta/Main.lean and "
        f"comparator/Main/{{Challenge.lean, Solution.lean, config.json}} together{hint}, or run "
        f"./gen_certificates.sh, which does it.")


def main() -> None:
    ap = argparse.ArgumentParser(usage="gen_count_certificate.py <out.lean> "
                                       "[--gram STORE] [--height H] [<store>…]")
    ap.add_argument("out", type=Path)
    ap.add_argument("stores", nargs="*", type=Path,
                    help="zero stores; default every store under python/out/, as "
                         "gen_zero_certificates.py")
    ap.add_argument("--gram", type=Path, help="the gram store (default: the one under python/out/)")
    ap.add_argument("--height", type=int, help="headline height, at most ⌊gp1.fst⌋ (the default)")
    args = ap.parse_args()
    stores = args.stores or default_stores()
    gram = args.gram or default_gram()

    head = gram_head(gram)
    height = math.floor(head)
    if args.height is not None:
        if args.height > height:
            raise SystemExit(f"--height {args.height} is above the first gram point {head}")
        height = args.height
    check_heights(height, math.floor(head))

    # `norm_num` must see through whatever wrapper constructors the last batch built its
    # endpoints with, exactly as a seam must; only the shared plan knows which batch that is.
    last_ref = plan_batches(stores)[-1][0]
    unfolds = "".join(", " + u for u in last_ref.dialect.seam_unfold)

    srcs = "\n".join(f"  {s.resolve().relative_to(ROOT)}" for s in stores)
    write_module(args.out, gen_count_certificate(unfolds, srcs))
    print(f"wrote {args.out} (certifiedZeroCount, last batch {last_ref.qual})")


if __name__ == "__main__":
    main()
